// serde_core/src/ser/impls.rs:685-696 -- `serialize_struct("Duration", 2)` with
// `secs` from `as_secs()` (u64) and `nanos` from `subsec_nanos()` (u32).
//
// Named rather than inlined, so it keeps a single shared definition in the output the
// way the hand-written schema had it.
impl PostcardSchema for core::time::Duration {
    fn type_id() -> Option<TypeId> {
        Some(TypeId { module: "core::time", ident: "Duration", args: Vec::new() })
    }

    fn register(reg: &mut Registry) {
        let id = Self::type_id().unwrap();
        if !reg.begin(id.clone()) {
            return;
        }
        let def = Def::Struct(alloc::vec![("secs", Node::U64), ("nanos", Node::U32)]);
        reg.finish(id, def);
    }

    fn node(reg: &mut Registry) -> Node {
        let id = Self::type_id().unwrap();
        Self::register(reg);
        reg.reference(id)
    }
}

// heapless 0.9.3, src/ser.rs. Implemented on the generic types so the `Fnv*` aliases
// (index_map.rs:70, index_set.rs:49) are covered without naming them.
#[cfg(feature = "heapless")]
mod heapless_impls {
    use super::*;

    // src/ser.rs:112 -- `serialize_map`.
    impl<K: PostcardSchema, V: PostcardSchema, S, const N: usize> PostcardSchema
        for heapless::index_map::IndexMap<K, V, S, N>
    {
        fn node(reg: &mut Registry) -> Node {
            Node::Map { key: Box::new(K::node(reg)), value: Box::new(V::node(reg)) }
        }
    }

    // src/ser.rs:44 -- `serialize_seq`, not a set. The data model has no set concept
    // and the TypeScript vocabulary has no set combinator; a set is a sequence that
    // happens to be unique. `Option<FnvIndexSet<Weekday, 8>>` on `ScheduleTrigger` is
    // the only user in this tree.
    impl<T: PostcardSchema, S, const N: usize> PostcardSchema
        for heapless::index_set::IndexSet<T, S, N>
    {
        fn node(reg: &mut Registry) -> Node {
            Node::Seq(Box::new(T::node(reg)))
        }
    }

    // src/ser.rs:60 -- `serialize_seq`.
    //
    // Written against the `Vec<T, N>` alias (vec/mod.rs:277) with its default
    // `LenT = usize` rather than against `VecInner`, which is what every use in this
    // tree looks like. A non-default `LenT` would be a compile error here rather than
    // a wrong schema.
    impl<T: PostcardSchema, const N: usize> PostcardSchema for heapless::Vec<T, N> {
        fn node(reg: &mut Registry) -> Node {
            Node::Seq(Box::new(T::node(reg)))
        }
    }

    // src/ser.rs:144 -- `serialize_str`. The capacity is a Rust-side bound only; it
    // does not appear on the wire, so `String<32>` and `String<96>` are both `Str`.
    impl<const N: usize> PostcardSchema for heapless::String<N> {
        fn node(_reg: &mut Registry) -> Node {
            Node::Str
        }
    }
}

// chrono 0.4.45. Every one of these serializes via `collect_str` with NO
// `is_human_readable` branch anywhere in the crate, so they are strings even in a
// binary format. Postcard implements `collect_str` (src/ser/serializer.rs:321) with the
// same encoding as `serialize_str`, so this holds in no_std.
//
// Checked individually rather than assumed, because "binary format therefore compact
// timestamp" is the natural guess and it is wrong:
//   Weekday       -- weekday.rs:275          -> "Mon".."Sun"
//   NaiveDateTime -- naive/datetime/serde.rs -> "2015-09-05T23:56:04"
//   NaiveDate     -- naive/date/mod.rs       -> "2015-09-05"
//   NaiveTime     -- naive/time/serde.rs     -> "23:56:04"
//   DateTime<Tz>  -- datetime/serde.rs       -> RFC3339
#[cfg(feature = "chrono")]
mod chrono_impls {
    use super::*;

    macro_rules! chrono_str {
        ($($ty:ty),* $(,)?) => {
            $(
                impl PostcardSchema for $ty {
                    fn node(_reg: &mut Registry) -> Node {
                        Node::Str
                    }
                }
            )*
        };
    }

    chrono_str!(
        chrono::NaiveDateTime,
        chrono::NaiveDate,
        chrono::NaiveTime,
        chrono::Weekday,
        chrono::Month,
    );

    impl<Tz: chrono::TimeZone> PostcardSchema for chrono::DateTime<Tz> {
        fn node(_reg: &mut Registry) -> Node {
            Node::Str
        }
    }
}
