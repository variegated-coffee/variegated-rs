//! Impls for types this crate does not define.
//!
//! Everything here is a type with no field *names* that could be wrong -- primitives,
//! containers, and a couple of foreign types whose serde representation is fixed and
//! verifiable from serde's own source. Structs with named fields are deliberately
//! absent: see the note on [`PostcardSchema`](crate::PostcardSchema) about hand-written
//! impls being invisible to a byte-level round-trip check.
//!
//! Each non-obvious mapping below cites the serde or upstream source it was checked
//! against, because "what does serde actually do here" is the entire correctness
//! question and it is not always what the Rust type suggests.

use alloc::boxed::Box;
use alloc::collections::{BTreeMap, BTreeSet};
use alloc::string::String;
use alloc::vec::Vec;

use crate::{Def, Node, PostcardSchema, Registry, TypeId};

macro_rules! primitive {
    ($($ty:ty => $node:ident),* $(,)?) => {
        $(
            impl PostcardSchema for $ty {
                fn node(_reg: &mut Registry) -> Node {
                    Node::$node
                }
            }
        )*
    };
}

primitive! {
    bool => Bool,
    i8 => I8, i16 => I16, i32 => I32, i64 => I64, i128 => I128,
    u8 => U8, u16 => U16, u32 => U32, u64 => U64, u128 => U128,
    f32 => F32, f64 => F64,
    char => Char,
    str => Str,
    String => Str,
}

// serde_core/src/ser/impls.rs:28 -- `primitive_impl!(usize, serialize_u64 as u64)`.
// Width-independent: `usize` is u64 in the data model on every target. Kept as its own
// node so the consumer must make a deliberate decision rather than inheriting a guess.
impl PostcardSchema for usize {
    fn node(_reg: &mut Registry) -> Node {
        Node::Usize
    }
}

impl PostcardSchema for isize {
    fn node(_reg: &mut Registry) -> Node {
        Node::Isize
    }
}

impl PostcardSchema for () {
    fn node(_reg: &mut Registry) -> Node {
        Node::Unit
    }
}

impl<T: PostcardSchema + ?Sized> PostcardSchema for &T {
    fn type_id() -> Option<TypeId> {
        T::type_id()
    }
    fn register(reg: &mut Registry) {
        T::register(reg);
    }
    fn node(reg: &mut Registry) -> Node {
        T::node(reg)
    }
}

impl<T: PostcardSchema + ?Sized> PostcardSchema for Box<T> {
    fn type_id() -> Option<TypeId> {
        T::type_id()
    }
    fn register(reg: &mut Registry) {
        T::register(reg);
    }
    fn node(reg: &mut Registry) -> Node {
        T::node(reg)
    }
}

impl<T: PostcardSchema> PostcardSchema for Option<T> {
    fn node(reg: &mut Registry) -> Node {
        Node::Option(Box::new(T::node(reg)))
    }
}

// `Vec<u8>` maps to a sequence of u8, NOT to `Bytes`. serde's blanket
// `impl Serialize for [T]` calls `serialize_seq`; only an explicit
// `serialize_bytes` (via `serde_bytes` or a manual impl) produces a byte string.
// Postcard happens to encode both identically, so this choice is invisible on the
// wire -- but it is visible in the generated TypeScript type, where the difference is
// `number[]` versus `Uint8Array`.
impl<T: PostcardSchema> PostcardSchema for Vec<T> {
    fn node(reg: &mut Registry) -> Node {
        Node::Seq(Box::new(T::node(reg)))
    }
}

impl<T: PostcardSchema> PostcardSchema for [T] {
    fn node(reg: &mut Registry) -> Node {
        Node::Seq(Box::new(T::node(reg)))
    }
}

// serde_core/src/ser/impls.rs:145-171 -- arrays go through `serialize_tuple($len)`,
// generated by `array_impls!` for N in 1..=32 only.
//
// This is the mapping most likely to be got wrong, and it fails loudly when it is: a
// tuple has NO length prefix, so reaching for `Seq` (or `Bytes`) here would insert a
// spurious varint and shift every subsequent field. `[u8; 6]` is six bytes, not seven.
impl<T: PostcardSchema, const N: usize> PostcardSchema for [T; N] {
    fn node(reg: &mut Registry) -> Node {
        let inner = T::node(reg);
        Node::Tuple(alloc::vec![inner; N])
    }
}

impl<K: PostcardSchema, V: PostcardSchema> PostcardSchema for BTreeMap<K, V> {
    fn node(reg: &mut Registry) -> Node {
        Node::Map { key: Box::new(K::node(reg)), value: Box::new(V::node(reg)) }
    }
}

impl<T: PostcardSchema> PostcardSchema for BTreeSet<T> {
    fn node(reg: &mut Registry) -> Node {
        Node::Seq(Box::new(T::node(reg)))
    }
}

macro_rules! tuple {
    ($($name:ident),+) => {
        impl<$($name: PostcardSchema),+> PostcardSchema for ($($name,)+) {
            fn node(reg: &mut Registry) -> Node {
                Node::Tuple(alloc::vec![$($name::node(reg)),+])
            }
        }
    };
}

